export const OCCUPATIONS: readonly OccupationDefinition[] = ROWS.map(
  ([id, title, industryId, education, field, skills, pay, maxLevel, options]) => ({
    id,
    title,
    industryId,
    education,
    field,
    skills,
    pay,
    maxLevel,
    teen: options?.teen ?? false,
    minSkill: options?.minSkill ?? 0,
    minExperienceMonths: options?.minExperienceMonths ?? 0,
    hidden: options?.hidden ?? false,
    licence: options?.licence ?? null,
  }),
);

const BY_ID = new Map(OCCUPATIONS.map((o) => [o.id, o]));
const INDUSTRY_BY_ID = new Map(INDUSTRIES.map((i) => [i.id, i]));

export function findOccupation(id: string): OccupationDefinition | undefined {
  return BY_ID.get(id);
}

export function getOccupation(id: string): OccupationDefinition {
  const occupation = BY_ID.get(id);
  if (!occupation) throw new Error(`Unknown occupation ${id}`);
  return occupation;
}

export function industryName(id: string): string {
  return INDUSTRY_BY_ID.get(id)?.name ?? id;
}

/** Pay multiplier per seniority level, percent. */
export const LEVEL_PAY = [100, 130, 170, 230, 320] as const;

export function jobTitle(occupation: OccupationDefinition, level: number): string {
  if (occupation.maxLevel === 0) return occupation.title;
  const base = occupation.title;
  // Keep acronyms ("UX designer", "IT support") as written.
  const lower = /^[A-Z]{2}/.test(base) ? base : base.charAt(0).toLowerCase() + base.slice(1);
  switch (level) {
    case 0:
      return occupation.education === 'none' || occupation.education === 'upperSecondary'
        ? base
        : `Junior ${lower}`;
    case 1:
      return occupation.education === 'none' || occupation.education === 'upperSecondary'
        ? `Experienced ${lower}`
        : base;
    case 2:
      return `Senior ${lower}`;
    case 3:
      return `Lead ${lower}`;
    default:
      return `Head of ${industryName(occupation.industryId).toLowerCase()} (${lower})`;
  }
}

const EDUCATION_RANK: Record<EducationLevel, number> = {
  none: 0,
  upperSecondary: 1,
  diploma: 2,
  bachelor: 3,
  master: 4,
};

/** Highest education level and fields from a list of qualifications. */
export function educationProfile(qualifications: readonly string[]): {
  level: EducationLevel;
  fields: Map<string, EducationLevel>;
} {
  let level: EducationLevel = 'none';
  const fields = new Map<string, EducationLevel>();
  for (const q of qualifications) {
    const [kind = '', field] = q.split(':');
    let qLevel: EducationLevel | null = null;
    if (kind === 'upperSecondary') qLevel = 'upperSecondary';
    else if (kind === 'diploma' || kind === 'bachelor' || kind === 'master') qLevel = kind;
    if (qLevel === null) continue;
    if (EDUCATION_RANK[qLevel] > EDUCATION_RANK[level]) level = qLevel;
    if (field) {
      const previous = fields.get(field);
      if (!previous || EDUCATION_RANK[qLevel] > EDUCATION_RANK[previous]) fields.set(field, qLevel);
    }
  }
  return { level, fields };
}

/** Whether qualifications satisfy an occupation's education requirement. */
export function meetsEducation(
  occupation: OccupationDefinition,
  qualifications: readonly string[],
): boolean {
  const profile = educationProfile(qualifications);
  const need = EDUCATION_RANK[occupation.education];
  if (occupation.field === null) return EDUCATION_RANK[profile.level] >= need;
  const inField = profile.fields.get(occupation.field);
  return inField !== undefined && EDUCATION_RANK[inField] >= need;
}
