export interface OccupationDefinition {
  id: string;
  title: string;
  industryId: string;
  education: EducationLevel;
  /** Required field of study (programme id), or null for any. */
  field: string | null;
  skills: readonly SkillKey[];
  /** Entry pay, percent of the median monthly wage. */
  pay: number;
  maxLevel: number;
  /** Open to teenagers as part-time or casual work. */
  teen: boolean;
  /** Minimum average of the occupation's skills (fixed-point tenths). */
  minSkill: number;
  /** Industry experience needed even at the first advertised level. */
  minExperienceMonths: number;
  /** Not advertised on the job board (family roles). */
  hidden: boolean;
  /** Character flag a practitioner must hold (admission or registration; decision E93). */
  licence: string | null;
}

