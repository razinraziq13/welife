import { z } from 'zod';
/** Mirrors PROPERTY_KINDS in state/schema (kept here to avoid an import cycle). */
const PROPERTY_KINDS = ['apartment', 'house', 'commercial'] as const;

/**
 * Country institutions (spec §4 World/countries, §6 CountryProfile; Milestone 6).
 *
 * Citizenship and residence, visa routes, healthcare access for newcomers, law, religion,
 * military service, political offices, foreign property buyers and inheritance for the 20
 * launch countries.
 *
 * How this was researched: compiled from the official sources listed for each country, as
 * they stood in 2025-2026. Rules that changed recently were checked against current news and
 * law-firm summaries on 2026-11-18 (see `INSTITUTIONS_SOURCE.checked`). These are the rules
 * at the game's start; everything after that is simulated, not real-world fact (decision D4).
 * Parties are fictional (decision D5). Numbers are simplified for play: for example one
 * "skilled work" route stands for each country's main skilled-worker visas.
 */

export const VISA_ROUTES = ['work', 'study', 'family', 'investor'] as const;
export type VisaRoute = (typeof VISA_ROUTES)[number];

export const QUALIFICATIONS = ['none', 'upperSecondary', 'diploma', 'bachelor'] as const;
export type Qualification = (typeof QUALIFICATIONS)[number];

export const RELIGIONS = [
  'none',
  'christianity',
  'islam',
  'hinduism',
  'buddhism',
  'sikhism',
  'judaism',
  'shinto',
  'taoism',
  'folk',
  'other',
] as const;
export type Religion = (typeof RELIGIONS)[number];

export const OFFICE_LEVELS = ['local', 'legislature', 'leader'] as const;
export type OfficeLevel = (typeof OFFICE_LEVELS)[number];

const Months = z.number().int().min(0).max(5000);

export const RouteRuleSchema = z
  .object({
    available: z.boolean(),
    name: z.string().min(2).max(80),
    minAge: z.number().int().min(0).max(80),
    /** Upper age limit, if any (points-tested routes). */
    maxAge: z.number().int().min(18).max(99).nullable(),
    qualification: z.enum(QUALIFICATIONS),
    /** Work experience needed instead of, or as well as, the qualification (months). */
    experienceMonths: Months,
    /** Investment or funds that must be held, in months of the local median wage. */
    capitalMonths: Months,
    processingMonths: z.number().int().min(1).max(24),
    /** Application fee, percent of the local median monthly wage. */
    feePercent: z.number().int().min(0).max(2000),
    /** Approval chance for an eligible applicant, basis points. */
    approvalBp: z.number().int().min(0).max(10_000),
    /** How long the visa lasts before it must be renewed (months). */
    durationMonths: z.number().int().min(6).max(240),
    workRights: z.enum(['full', 'limited', 'none']),
    /** Grants permanent residence straight away (points-tested skilled migration). */
    grantsPermanent: z.boolean(),
    /** Time on this visa counts towards permanent residence. */
    leadsToPermanent: z.boolean(),
    note: z.string().max(240),
  })
  .strict();
export type RouteRule = z.infer<typeof RouteRuleSchema>;

const OfficeSchema = z
  .object({
    title: z.string().min(2).max(80),
    minAge: z.number().int().min(18).max(60),
    termYears: z.number().int().min(1).max(7),
    /** How the office is filled. */
    selection: z.enum(['election', 'party', 'appointment']),
    /** Consecutive terms allowed (null = no limit). */
    termLimit: z.number().int().min(1).max(5).nullable(),
  })
  .strict();
export type OfficeRule = z.infer<typeof OfficeSchema>;

export const InstitutionsSchema = z
  .object({
    code: z.string().length(2),
    citizenship: z
      .object({
        /** Citizenship by birth in the country. */
        birthright: z.enum(['unconditional', 'parentResident', 'atMajority', 'none']),
        descent: z.boolean(),
        /** Years of legal residence before permanent residence (null = no general route). */
        permanentYears: z.number().int().min(1).max(20).nullable(),
        /** Years of residence before naturalisation (null = practically unavailable). */
        naturalisationYears: z.number().int().min(1).max(30).nullable(),
        /** Naturalisation counts years from arrival, or only years as a permanent resident. */
        countsFrom: z.enum(['arrival', 'permanent']),
        requiresPermanent: z.boolean(),
        test: z.enum(['none', 'language', 'civics', 'both']),
        /** Holding another citizenship: allowed, restricted (renounce on naturalising), or not. */
        dual: z.enum(['allowed', 'restricted', 'none']),
        note: z.string().max(300),
      })
      .strict(),
    visas: z.record(z.enum(VISA_ROUTES), RouteRuleSchema),
    healthcare: z
      .object({
        /** Share of the public coverage that temporary residents get, percent. */
        visitorCoveragePercent: z.number().int().min(0).max(100),
        /** Typical wait for non-urgent public treatment, months. */
        publicWaitMonths: z.number().int().min(0).max(12),
        note: z.string().max(240),
      })
      .strict(),
    law: z
      .object({
        system: z.enum(['common', 'civil', 'mixed', 'islamic']),
        majorityAge: z.number().int().min(15).max(21),
        drivingAge: z.number().int().min(15).max(21),
        /** Legal drinking age (null = alcohol is prohibited). */
        drinkingAge: z.number().int().min(16).max(25).nullable(),
        marriageAge: z.number().int().min(16).max(22),
        /** Years after a sentence ends until a conviction is spent for most purposes. */
        recordSpentYears: z.number().int().min(1).max(30),
        juries: z.boolean(),
        note: z.string().max(240),
        /** Sensitive laws, described neutrally; hidden when the player filters them (D6). */
        sensitiveNote: z.string().max(300).default(''),
      })
      .strict(),
    religion: z
      .object({
        official: z.enum(RELIGIONS).nullable(),
        /** Leaving this faith is legally restricted for its members (modelled neutrally). */
        leavingRestricted: z.enum(RELIGIONS).nullable(),
        /** Population shares (percent, whole numbers adding to 100). */
        shares: z.array(z.tuple([z.enum(RELIGIONS), z.number().int().min(1).max(100)])).min(2),
        note: z.string().max(240),
      })
      .strict(),
    military: z
      .object({
        conscription: z.enum(['none', 'male', 'lottery', 'programme']),
        callUpAge: z.number().int().min(16).max(25),
        /** Last age at which someone can still be called up (deferments end here). */
        callUpUntil: z.number().int().min(16).max(40),
        serviceMonths: z.number().int().min(0).max(36),
        /** Share of those liable who actually serve, percent. */
        selectionPercent: z.number().int().min(0).max(100),
        deferForStudy: z.boolean(),
        volunteerAge: z.number().int().min(16).max(21),
        /** Who may enlist voluntarily. */
        volunteers: z.enum(['citizens', 'permanent', 'anyone']),
        /** Permanent residents are liable for conscription too. */
        permanentLiable: z.boolean(),
        note: z.string().max(300),
      })
      .strict(),
    politics: z
      .object({
        system: z.string().min(3).max(80),
        voteAge: z.number().int().min(16).max(25).nullable(),
        compulsoryVoting: z.boolean(),
        offices: z.record(z.enum(OFFICE_LEVELS), OfficeSchema.nullable()),
        /** The head of government must have been a citizen from birth. */
        leaderBirthCitizen: z.boolean(),
        /** Members of the legislature may hold no other citizenship. */
        singleCitizenship: z.boolean().default(false),
        parties: z.array(
          z.object({ id: z.string(), name: z.string(), position: z.string() }).strict(),
        ),
        note: z.string().max(300),
      })
      .strict(),
    property: z
      .object({
        /** What buyers without citizenship or permanent residence may do. */
        foreignBuyers: z.enum(['allowed', 'restricted', 'banned']),
        foreignKinds: z.array(z.enum(PROPERTY_KINDS)),
        /** Extra purchase tax for foreign buyers, basis points of the price. */
        surchargeBp: z.number().int().min(0).max(10_000),
        /** Minimum price for foreign buyers, months of the local median wage. */
        minPriceMonths: Months,
        /** Months of residence before a foreigner may buy. */
        minResidenceMonths: Months,
        note: z.string().max(300),
      })
      .strict(),
    inheritance: z
      .object({
        /** Top inheritance or estate tax rate, basis points (0 = none). */
        taxTopBp: z.number().int().min(0).max(10_000),
        /** Children (or other close family) are entitled to a fixed share. */
        forcedHeirship: z.boolean(),
        note: z.string().max(240),
      })
      .strict(),
    sources: z.array(z.object({ label: z.string().max(120), url: z.url() }).strict()).min(2),
  })
  .strict();
export type Institutions = z.infer<typeof InstitutionsSchema>;

