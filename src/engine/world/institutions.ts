type R = Partial<RouteRule> & { name: string };

const route = (r: R): RouteRule => ({
  available: true,
  minAge: 18,
  maxAge: null,
  qualification: 'none',
  experienceMonths: 0,
  capitalMonths: 0,
  processingMonths: 3,
  feePercent: 20,
  approvalBp: 8000,
  durationMonths: 36,
  workRights: 'full',
  grantsPermanent: false,
  leadsToPermanent: true,
  note: '',
  ...r,
});

const closed = (name: string, note: string): RouteRule =>
  route({ name, available: false, approvalBp: 0, leadsToPermanent: false, note });

const study = (r: Partial<RouteRule> = {}): RouteRule =>
  route({
    name: 'Student visa',
    minAge: 16,
    qualification: 'upperSecondary',
    processingMonths: 2,
    feePercent: 10,
    approvalBp: 8500,
    durationMonths: 36,
    workRights: 'limited',
    leadsToPermanent: false,
    ...r,
  });

const family = (r: Partial<RouteRule> = {}): RouteRule =>
  route({
    name: 'Spouse or partner visa',
    processingMonths: 4,
    feePercent: 25,
    approvalBp: 9000,
    durationMonths: 30,
    note: 'Needs a spouse who is a citizen or permanent resident here.',
    ...r,
  });

const office = (
  title: string,
  minAge: number,
  termYears: number,
  selection: OfficeRule['selection'] = 'election',
  termLimit: number | null = null,
): OfficeRule => ({ title, minAge, termYears, selection, termLimit });

function parties(demonym: string): Institutions['politics']['parties'] {
  return [
    { id: 'progress', name: `${demonym} Progress Party`, position: 'centre-left' },
    { id: 'unity', name: `${demonym} Unity Party`, position: 'centre' },
    { id: 'reform', name: `${demonym} Reform Party`, position: 'centre-right' },
  ];
}

const src = (label: string, url: string) => ({ label, url });

function define(input: z.input<typeof InstitutionsSchema>): Institutions {
  return InstitutionsSchema.parse(input);
}

